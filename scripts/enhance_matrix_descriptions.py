def lookup_desc(l1, l2, l3, l4, old: str) -> str:
    key = "|".join(str(x).strip() for x in [l1, l2, l3, l4])
    if key in DESC:
        return DESC[key]
    key2 = "|".join([str(l1).strip(), str(l2).strip().strip(), str(l3).strip(), str(l4).strip()])
    if key2 in DESC:
        return DESC[key2]
    if old and str(old).strip().lower() not in ("nan", ""):
        return str(old).strip()
    return f"提供「{l4}」能力，用于支撑{l1}场景下的{l2}相关工作。"


def main():
    if not INPUT.exists():
        raise FileNotFoundError(INPUT)

    shutil.copy2(INPUT, OUTPUT)
    wb = load_workbook(OUTPUT)
    ws = wb.worksheets[0]

    headers = [ws.cell(1, c).value for c in range(1, ws.max_column + 1)]
    col_idx = {h: i + 1 for i, h in enumerate(headers) if h}
    need = ["L1", "L2", "L3", "L4", "功能描述"]
    for n in need:
        if n not in col_idx:
            raise KeyError(f"缺少列: {n}")

    l1 = l2 = l3 = None
    updated = 0
    wrap = Alignment(horizontal="left", vertical="top", wrap_text=True)

    for r in range(2, ws.max_row + 1):
        v1, v2, v3, v4 = [ws.cell(r, col_idx[c]).value for c in ["L1", "L2", "L3", "L4"]]
        if v1 not in (None, ""):
            l1 = v1
        if v2 not in (None, ""):
            l2 = v2
        if v3 not in (None, ""):
            l3 = v3
        if v4 in (None, ""):
            continue
        old = ws.cell(r, col_idx["功能描述"]).value
        new = lookup_desc(l1, l2, l3, v4, old or "")
        if new != (old or ""):
            updated += 1
        cell = ws.cell(r, col_idx["功能描述"], new)
        cell.alignment = wrap

    ws.column_dimensions[ws.cell(1, col_idx["功能描述"]).column_letter].width = 56
    wb.save(OUTPUT)
    print(f"Read:  {INPUT}")
    print(f"Write: {OUTPUT}")
    print(f"Updated: {updated} rows")


if __name__ == "__main__":
    main()
